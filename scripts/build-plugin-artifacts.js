#!/usr/bin/env node
import { spawnSync } from 'node:child_process';
import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build as esbuild } from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const agentsCommBusDir = path.join(repoRoot, 'agents-comm-bus');
const agentsCommBusCoreDir = path.join(repoRoot, 'agents-comm-bus-core');
const mcpServerDir = path.join(repoRoot, 'mcp-server');
const hooksDir = path.join(repoRoot, 'hooks');
const skillsDir = path.join(repoRoot, 'skills');
const pluginsDir = path.join(repoRoot, 'plugins');
const schemaDir = path.join(agentsCommBusDir, 'src', 'storage', 'schema');

export const SUPPORTED_AGENTS = ['claude', 'codex'];
export const SUPPORTED_COMMS = ['telegram', 'matrix', 'discord', 'slack'];
export const COMM_IMPLEMENTATION_STATUS = {
  telegram: 'implemented',
  matrix: 'scaffold',
  discord: 'scaffold',
  slack: 'scaffold',
};

function hasFlag(flag) {
  return process.argv.includes(flag);
}

async function pathExists(target) {
  try {
    await stat(target);
    return true;
  } catch {
    return false;
  }
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, {
    cwd,
    stdio: 'inherit',
    env: process.env,
  });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed in ${cwd}`);
  }
}

async function ensureBuiltPackages({ buildDeps = false } = {}) {
  const required = [
    {
      cwd: agentsCommBusCoreDir,
      check: path.join(agentsCommBusCoreDir, 'dist', 'index.js'),
      label: 'agents-comm-bus-core',
    },
    {
      cwd: agentsCommBusDir,
      check: path.join(agentsCommBusDir, 'dist', 'serve.js'),
      label: 'agents-comm-bus',
    },
    {
      cwd: mcpServerDir,
      check: path.join(mcpServerDir, 'dist', 'server.js'),
      label: 'mcp-server',
    },
  ];

  for (const item of required) {
    if (buildDeps || !(await pathExists(item.check))) {
      console.log(`[build-plugin-artifacts] building ${item.label}`);
      run('npm', ['run', 'build'], item.cwd);
    }
  }
}

async function bundle(entryPoint) {
  const result = await esbuild({
    absWorkingDir: repoRoot,
    entryPoints: [entryPoint],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    write: false,
    banner: {
      js: "#!/usr/bin/env node\nimport { createRequire } from 'module'; const require = createRequire(import.meta.url);",
    },
    logLevel: 'silent',
  });
  return `${result.outputFiles[0].text.trim()}\n`;
}

function renderPlaceholderBundle(kind, comm) {
  return `#!/usr/bin/env node
const message = ${JSON.stringify(`agents-comm-bus ${kind} scaffold for ${comm} is present in the AGE-7 release layout, but the runtime implementation has not landed yet.`)};
export const scaffold = { kind: ${JSON.stringify(kind)}, comm: ${JSON.stringify(comm)} };
export function notImplemented() {
  throw new Error(message);
}
if (import.meta.url === new URL(process.argv[1], 'file://').href) {
  console.error(message);
  process.exit(1);
}
`;
}

function renderSkill(agent, comm, version) {
  const status = COMM_IMPLEMENTATION_STATUS[comm] === 'implemented' ? 'implemented' : 'scaffold-only';
  const description = COMM_IMPLEMENTATION_STATUS[comm] === 'implemented'
    ? `${comm} communication for ${agent} via the shared agents-comm-bus runtime.`
    : `${comm} plugin scaffold for ${agent}; release layout present but runtime adapter still pending.`;
  return `---
name: agents-comm-bus-${comm}
description: ${description}
version: ${version}
---

# agents-comm-bus ${comm} (${agent})

Status: ${status}

This plugin payload is generated by the AGE-7 build flow into plugins/${agent}/${comm}/.

What ships here:
- daemon.bundle.js
- ${comm}.adapter.bundle.js
- ${agent}-mcp-shim.js
- host-native plugin manifests
- reusable hook payloads

Notes:
- Telegram is the only fully implemented comm in this repository today.
- Matrix, Discord, and Slack payloads are scaffolds so the release matrix, marketplace pointers, and validation tooling can exercise the full 2 x 4 distribution shape without pretending the adapters are complete.
- Runtime state remains outside the plugin tree under ~/.agents-comm-bus/.
`;
}

function renderClaudePluginManifest(comm, version) {
  const implemented = COMM_IMPLEMENTATION_STATUS[comm] === 'implemented';
  return {
    name: `agents-comm-bus-${comm}`,
    version,
    description: implemented
      ? `${capitalize(comm)} messaging for Claude Code through the shared agents-comm-bus daemon.`
      : `${capitalize(comm)} scaffold for Claude Code through the shared agents-comm-bus daemon.`,
    author: { name: 'Satrio' },
    mcpServers: {
      [comm]: {
        command: 'node',
        args: [`\${CLAUDE_PLUGIN_ROOT}/${implemented ? 'claude-mcp-shim.js' : `${comm}-scaffold-mcp-shim.js`}`],
      },
    },
  };
}

function renderCodexPluginManifest(comm, version) {
  const implemented = COMM_IMPLEMENTATION_STATUS[comm] === 'implemented';
  return {
    name: `agents-comm-bus-${comm}`,
    version,
    description: implemented
      ? `${capitalize(comm)} messaging for Codex through the shared agents-comm-bus daemon.`
      : `${capitalize(comm)} scaffold for Codex through the shared agents-comm-bus daemon.`,
    author: { name: 'Satrio' },
    homepage: 'https://github.com/remingtonspaz/claude-code-telegram',
    repository: 'https://github.com/remingtonspaz/claude-code-telegram',
    license: 'MIT',
    keywords: [comm, 'messaging', 'agents-comm-bus', implemented ? 'remote-control' : 'scaffold'],
    skills: './skills/',
    interface: {
      displayName: capitalize(comm),
      shortDescription: implemented ? `Talk to Codex from ${capitalize(comm)}` : `${capitalize(comm)} release scaffold for Codex`,
      longDescription: implemented
        ? `${capitalize(comm)} messaging for Codex. The plugin talks to the shared agents-comm-bus daemon and keeps communication ownership outside the agent harness.`
        : `${capitalize(comm)} release scaffold for Codex. The plugin layout exists so CI, release tagging, and marketplace pointers can cover the full AGE-7 matrix while the runtime adapter is still pending.`,
      developerName: 'Satrio',
      category: 'Productivity',
      capabilities: ['Read', 'Write'],
      defaultPrompt: [implemented ? `Send a status update to my ${capitalize(comm)}` : `Explain the ${capitalize(comm)} scaffold status`],
    },
  };
}

function renderCodexMcpConfig(comm) {
  const implemented = COMM_IMPLEMENTATION_STATUS[comm] === 'implemented';
  return {
    mcpServers: {
      [comm]: {
        command: 'node',
        args: [`\${CODEX_PLUGIN_ROOT}/${implemented ? 'codex-mcp-shim.js' : `${comm}-scaffold-mcp-shim.js`}`],
      },
    },
  };
}

function capitalize(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

async function writeJson(target, value) {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

async function writeText(target, content) {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, content, 'utf8');
}

async function copyCommonPayload(targetDir) {
  await cp(hooksDir, path.join(targetDir, 'hooks'), { recursive: true });
  await cp(schemaDir, path.join(targetDir, 'storage', 'schema'), { recursive: true });
}

async function generatePluginArtifacts({ buildDeps = false } = {}) {
  await ensureBuiltPackages({ buildDeps });

  const rootPackage = JSON.parse(await readFile(path.join(repoRoot, 'package.json'), 'utf8'));
  const version = rootPackage.version;
  const daemonBundle = await bundle(path.join(agentsCommBusDir, 'src', 'serve.ts'));
  const telegramAdapterBundle = await bundle(path.join(agentsCommBusDir, 'src', 'adapters', 'comm', 'telegram', 'factory.ts'));
  const telegramMcpShimBundle = await bundle(path.join(mcpServerDir, 'server.js'));

  await rm(pluginsDir, { recursive: true, force: true });

  for (const agent of SUPPORTED_AGENTS) {
    for (const comm of SUPPORTED_COMMS) {
      const pluginRoot = path.join(pluginsDir, agent, comm);
      const implemented = COMM_IMPLEMENTATION_STATUS[comm] === 'implemented';
      const adapterBundle = implemented ? telegramAdapterBundle : renderPlaceholderBundle('adapter', comm);
      const shimFileName = implemented ? `${agent}-mcp-shim.js` : `${comm}-scaffold-mcp-shim.js`;
      const shimBundle = implemented ? telegramMcpShimBundle : renderPlaceholderBundle('mcp shim', comm);

      await writeText(path.join(pluginRoot, 'daemon.bundle.js'), daemonBundle);
      await writeText(path.join(pluginRoot, `${comm}.adapter.bundle.js`), adapterBundle);
      await writeText(path.join(pluginRoot, shimFileName), shimBundle);
      await writeText(path.join(pluginRoot, 'skills', `${comm}.md`), renderSkill(agent, comm, version));
      await copyCommonPayload(pluginRoot);

      if (agent === 'claude') {
        await writeJson(path.join(pluginRoot, '.claude-plugin', 'plugin.json'), renderClaudePluginManifest(comm, version));
      } else {
        await writeJson(path.join(pluginRoot, '.codex-plugin', 'plugin.json'), renderCodexPluginManifest(comm, version));
        await writeJson(path.join(pluginRoot, '.mcp.json'), renderCodexMcpConfig(comm));
      }
    }
  }

  const summary = [];
  for (const agent of SUPPORTED_AGENTS) {
    for (const comm of SUPPORTED_COMMS) {
      summary.push(`${agent}/${comm}:${COMM_IMPLEMENTATION_STATUS[comm]}`);
    }
  }
  console.log(`[build-plugin-artifacts] generated ${summary.join(', ')}`);
}

export async function buildPluginArtifacts(options = {}) {
  await generatePluginArtifacts(options);
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  buildPluginArtifacts({ buildDeps: hasFlag('--build-deps') }).catch((error) => {
    console.error(error instanceof Error ? error.stack ?? error.message : String(error));
    process.exit(1);
  });
}
